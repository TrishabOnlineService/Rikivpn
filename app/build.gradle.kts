tasks.register("encryptServersConfig") {
    val inputFile = file("servers.json")
    val outputFile = file("src/main/assets/config.bin")
    
    inputs.file(inputFile).optional(true)
    outputs.file(outputFile)
    
    doLast {
        if (!inputFile.exists()) {
            println("No servers.json found, skipping encryption.")
            if (!outputFile.parentFile.exists()) outputFile.parentFile.mkdirs()
            if (!outputFile.exists()) outputFile.writeBytes(ByteArray(0))
            return@doLast
        }
        val plaintext = inputFile.readText()
        val secretString = "my-super-secret-key-32bytes-long" 
        val keyBytes = secretString.toByteArray().copyOf(32)
        val secretKey = SecretKeySpec(keyBytes, "AES")
        
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        val iv = ByteArray(12)
        SecureRandom().nextBytes(iv)
        val spec = GCMParameterSpec(128, iv)
        
        cipher.init(Cipher.ENCRYPT_MODE, secretKey, spec)
        val ciphertext = cipher.doFinal(plaintext.toByteArray())
        
        val outputBytes = iv + ciphertext
        if (!outputFile.parentFile.exists()) outputFile.parentFile.mkdirs()
        outputFile.writeBytes(outputBytes)
        println("Encrypted servers.json to config.bin")
    }
}

tasks.whenTaskAdded {
